const STRINGS: Record<Lang, Record<string, string>> = { es: ES, en: EN };

interface I18nState {
  lang: Lang;
  setLang: (l: Lang) => Promise<void>;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nState | null>(null);

/**
 * El idioma es configuración GLOBAL: vive en `settings.language` y llega a los
 * demás terminales por la suscripción realtime de settings. localStorage se usa
 * solo como caché para pintar el login antes de que carguen los ajustes.
 */
export function I18nProvider({
  language,
  onLanguageChanged,
  children,
}: {
  /** Idioma guardado en los ajustes; `null` mientras la base aún carga. */
  language: string | null;
  onLanguageChanged: () => Promise<void>;
  children: ReactNode;
}) {
  // Inglés mientras la base carga y en una instalación nueva. Solo el español
  // ya guardado antes gana a ese valor de partida.
  const [cached, setCached] = useState<Lang>(() =>
    localStorage.getItem(CACHE_KEY) === "es" ? "es" : "en",
  );

  const lang: Lang =
    language === "en" || language === "es" ? language : cached;

  useEffect(() => {
    localStorage.setItem(CACHE_KEY, lang);
    document.documentElement.lang = lang;
    setCached(lang);
  }, [lang]);

  const setLang = useCallback(
    async (l: Lang) => {
      setCached(l); // respuesta inmediata
      try {
        await exec("UPDATE settings SET language = $1 WHERE id = 1", [l]);
        await onLanguageChanged();
      } catch (e) {
        toast.error(e instanceof Error ? e.message : String(e));
      }
    },
    [onLanguageChanged],
  );

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      let s = STRINGS[lang][key] ?? ES[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          // split/join en vez de replaceAll: el target de tsconfig es ES2020.
          s = s.split(`{${k}}`).join(String(v));
        }
      }
      return s;
    },
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside <I18nProvider>");
  return ctx;
}
